// gensyscalltable は golang.org/x/sys/unix の zsysnum_linux_<arch>.go から
// syscall 番号 → syscall 名のテーブルを生成する。
//
// 使い方:
//
//	go run ./tools/gensyscalltable -arch amd64 -out pkg/gvisor/syscalltable_amd64.go
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

var syscallConstantPattern = regexp.MustCompile(`^\s*SYS_([A-Z0-9_]+)\s*=\s*(\d+)\s*$`)

func main() {
	targetArch := flag.String("arch", "", "対象アーキテクチャ (amd64 / arm64)")
	outputPath := flag.String("out", "", "出力する Go ファイルのパス")
	flag.Parse()
	if *targetArch == "" || *outputPath == "" {
		flag.Usage()
		os.Exit(2)
	}

	xsysDir, err := findModuleDir("golang.org/x/sys")
	if err != nil {
		log.Fatal(err)
	}
	sourcePath := filepath.Join(xsysDir, "unix", fmt.Sprintf("zsysnum_linux_%s.go", *targetArch))
	syscallNamesByNumber, err := parseSyscallNumbers(sourcePath)
	if err != nil {
		log.Fatal(err)
	}

	generatedSource, err := renderTable(*targetArch, sourcePath, syscallNamesByNumber)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outputPath, generatedSource, 0o644); err != nil {
		log.Fatal(err)
	}
}

func findModuleDir(modulePath string) (string, error) {
	output, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", modulePath).Output()
	if err != nil {
		return "", fmt.Errorf("go list -m %s: %w", modulePath, err)
	}
	return strings.TrimSpace(string(output)), nil
}

func parseSyscallNumbers(sourcePath string) (map[uint64]string, error) {
	sourceFile, err := os.Open(sourcePath)
	if err != nil {
		return nil, err
	}
	defer sourceFile.Close()

	syscallNamesByNumber := make(map[uint64]string)
	scanner := bufio.NewScanner(sourceFile)
	for scanner.Scan() {
		match := syscallConstantPattern.FindStringSubmatch(scanner.Text())
		if match == nil {
			continue
		}
		syscallNumber, err := strconv.ParseUint(match[2], 10, 64)
		if err != nil {
			return nil, err
		}
		// 同じ番号に複数の別名がある場合は最初に出現した名前を採用する。
		if _, exists := syscallNamesByNumber[syscallNumber]; !exists {
			syscallNamesByNumber[syscallNumber] = strings.ToLower(match[1])
		}
	}
	return syscallNamesByNumber, scanner.Err()
}

func renderTable(targetArch, sourcePath string, syscallNamesByNumber map[uint64]string) ([]byte, error) {
	syscallNumbers := make([]uint64, 0, len(syscallNamesByNumber))
	for syscallNumber := range syscallNamesByNumber {
		syscallNumbers = append(syscallNumbers, syscallNumber)
	}
	slices.Sort(syscallNumbers)

	var buffer bytes.Buffer
	fmt.Fprintf(&buffer, "// Code generated by tools/gensyscalltable from %s. DO NOT EDIT.\n\n", filepath.Base(sourcePath))
	fmt.Fprintf(&buffer, "//go:build %s\n\n", targetArch)
	fmt.Fprintf(&buffer, "package gvisor\n\n")
	fmt.Fprintf(&buffer, "var syscallNamesByNumber = map[uint64]string{\n")
	for _, syscallNumber := range syscallNumbers {
		fmt.Fprintf(&buffer, "\t%d: %q,\n", syscallNumber, syscallNamesByNumber[syscallNumber])
	}
	fmt.Fprintf(&buffer, "}\n")
	return format.Source(buffer.Bytes())
}
